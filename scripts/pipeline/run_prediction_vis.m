% run_prediction_vis  Generate dense predictions and visualise SERS metrics.
%
% Thin CLI entry point that delegates to the modular orchestration layer.
% All domain logic lives in runPredictionVisWorkflow; this script only
% assembles configuration.
%
% To customise, modify the predictionVisConfig call below.
% The same workflow can be called from uihtml apps via:
%     results = runPredictionVisWorkflow(cfg, htmlReporter);
%
% See also: predictionVisConfig, runPredictionVisWorkflow, ProgressReporter

%% Configuration
workDir = string(pwd);

cfg = predictionVisConfig( ...
    WorkDir=workDir, ...
    ModelFile="sers_dnn_model_sphere_785_new.mat", ...
    RiCsvFile="McPeak.csv", ...
    ...
    ... % Grid parameters
    LambdaLaser=785, ...
    PLimits=[750, 950], ...
    RLimits=[50, 450], ...
    StokesShiftLimits=[100, 3600], ...
    Resolution=0.75, ...
    StokesShiftResolution=2, ...
    ...
    ... % Metrics
    Metrics=["Absorptance", "EF_vol", "EF_surf"], ...
    ...
    ... % Prediction control
    RecomputePredictions=false, ...
    ...
    ... % Analyte weighting
    UseAnalyteWeighting=true, ...
    AnalyteRamanSpectrumFile="AnalyteSpectrum_electrolyte.dat", ...
    ...
    ... % Export / visualisation
    ExportPredictions=true, ...
    ExportGraphics=true, ...
    ExportVideo=false);

%% Run workflow
reporter = ProgressReporter.console();
results = runPredictionVisWorkflow(cfg, reporter);

%% Summary
fprintf("\nPrediction-vis workflow complete.\n");
fprintf("  Geometries: %d, Wavelengths: %d\n", ...
    size(results.allData.lambda, 1), size(results.allData.lambda, 2));
fprintf("  Elapsed: %.1f s\n", results.elapsedTotal);